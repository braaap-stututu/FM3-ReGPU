#!/usr/bin/env python3
"""Weak fallbacks for every kernel/XAM import the recompiled code calls.

  py -3 -I tools/genstubs.py out/ppc/ppc_recomp_shared.h <out.cpp>

Each stub logs its first call (name and caller) and returns 0; a real implementation anywhere
in src/ overrides it (the stubs are weak). Run by CMake into the build folder, so the list
always matches out/ppc. Prints the number of stubs. Own code (FM3 project).
"""
import re
import sys

if len(sys.argv) != 3:
    sys.exit(__doc__)
names = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__([A-Za-z_]\w*)\)", open(sys.argv[1]).read())))
names = [n for n in names if not n.startswith("sub_")]
with open(sys.argv[2], "w", newline="\n") as out:
    out.write("// Generated by tools/genstubs.py from out/ppc/ppc_recomp_shared.h: do not edit.\n")
    out.write("// Weak fallback for every import; each logs its first call and returns 0.\n")
    out.write('#include "kernel/imports.h"\n\n')
    for n in names:
        out.write(f"__attribute__((weak)) PPC_FUNC(__imp__{n})\n{{\n")
        out.write(f'    LOG_ONCE("unimplemented import {n} (lr %08llX)", ctx.lr);\n')
        out.write("    ctx.r3.u64 = 0;\n}\n\n")
print(len(names), "stubs")
