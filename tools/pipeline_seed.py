"""Builds src/pipeline_seed.h (regpu::Host::pipelineSeed): every pipeline in the given pipelines.manifest
files merged, so a first boot builds them behind ReGPU's overlay instead of on first sight in a race.

  python -I tools/pipeline_seed.py <manifest or folder>... [--out src/pipeline_seed.h] [--fresh]

The existing header's lines are kept (merged in) unless --fresh: a manifest may lack lines an
older seed had (session 28: this PC's manifest had no "V" vertex-variant lines left).

A manifest holds hashes and render state only ("P vs ps blend depth stencilMaskMode flags [bias...]",
"V ..." vertex-shader variants), no game data. Folders are searched for files named pipelines.manifest.
Lines are de-duplicated and sorted so the header only changes when the set does.
"""
import os
import sys


def manifests(paths):
    for p in paths:
        if os.path.isdir(p):
            for d, _, fs in os.walk(p):
                for f in fs:
                    if f == "pipelines.manifest":
                        yield os.path.join(d, f)
        else:
            yield p


def main(argv):
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "pipeline_seed.h")
    if "--out" in argv:
        i = argv.index("--out")
        out = argv[i + 1]
        del argv[i:i + 2]
    fresh = "--fresh" in argv
    if fresh:
        argv.remove("--fresh")
    if not argv:
        print(__doc__)
        return 1
    lines, files = set(), 0
    if not fresh and os.path.exists(out):
        with open(out, encoding="ascii", errors="replace") as f:
            for line in f:
                line = line.strip()
                if line.startswith('"P ') or line.startswith('"V '):
                    lines.add(" ".join(line[1:].replace("\\n", "").rstrip('",').split()))
    for m in manifests(argv):
        files += 1
        with open(m, encoding="ascii", errors="replace") as f:
            for line in f:
                line = line.strip()
                parts = line.split()
                hexish = all(c in "0123456789abcdef:." for c in "".join(parts[1:]).lower())
                if hexish and ((parts[:1] == ["P"] and len(parts) >= 7) or (parts[:1] == ["V"] and len(parts) >= 4)):
                    lines.add(" ".join(parts))
    p = sorted(l for l in lines if l.startswith("P "))
    v = sorted(l for l in lines if l.startswith("V "))
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/pipeline_seed.py from %d pipelines.manifest file(s): %d pipelines, %d vertex shader variants.\n"
                % (files, len(p), len(v)))
        f.write("#pragma once\n\n// pipelines.manifest lines (regpu::Host::pipelineSeed): hashes and render state, no game data.\n")
        f.write("inline const char kPipelineSeed[] =\n")
        for l in v + p:
            f.write('    "%s\\n"\n' % l)
        f.write('    "";\n')
    print("%s: %d pipelines, %d variants from %d file(s)" % (out, len(p), len(v), files))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
